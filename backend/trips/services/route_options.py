"""Get three distinct truck route options for a trip.

TomTom usually returns three routes when asked for two alternatives, but not
always (e.g. Dallas -> Denver returns two). Missing options are generated by
routing through a detour waypoint to the side of the direct line, and kept
only if they are distinct from the existing routes and not unreasonably slow.
"""

from concurrent.futures import ThreadPoolExecutor
from datetime import datetime

from trips.clients import tomtom
from trips.clients.tomtom import TruckRoute
from trips.domain.route_geometry import detour_point, shared_fraction
from trips.domain.sampling import LatLon
from trips.exceptions import NoRouteFound

TARGET_ROUTE_COUNT = 3
# Sideways offsets in order of preference, as a fraction of the straight-line distance.
DETOUR_OFFSETS = (0.15, -0.15, 0.30, -0.30)
MAX_SHARED_FRACTION = 0.8
MAX_DURATION_RATIO = 1.5  # vs. the fastest route


def get_route_options(
    origin: LatLon,
    destination: LatLon,
    departure: datetime,
    vehicle_weight_kg: int,
) -> tuple[list[TruckRoute], list[str]]:
    """Return up to three routes and any warnings for the user."""
    routes = tomtom.truck_routes(
        [origin, destination], departure, vehicle_weight_kg, max_alternatives=TARGET_ROUTE_COUNT - 1
    )[:TARGET_ROUTE_COUNT]
    provider_count = len(routes)

    if len(routes) < TARGET_ROUTE_COUNT:
        for candidate in _detour_routes(origin, destination, departure, vehicle_weight_kg):
            if len(routes) == TARGET_ROUTE_COUNT:
                break
            if candidate and _is_useful_alternative(candidate, routes):
                routes.append(candidate)

    return routes, _warnings(provider_count, len(routes))


def _detour_routes(
    origin: LatLon, destination: LatLon, departure: datetime, vehicle_weight_kg: int
) -> list[TruckRoute | None]:
    """One route per detour offset (None if unreachable), requested in parallel."""

    def route_via(offset: float) -> TruckRoute | None:
        via = detour_point(origin, destination, offset)
        try:
            return tomtom.truck_routes([origin, via, destination], departure, vehicle_weight_kg)[0]
        except NoRouteFound:
            return None

    with ThreadPoolExecutor(max_workers=len(DETOUR_OFFSETS)) as pool:
        return list(pool.map(route_via, DETOUR_OFFSETS))


def _is_useful_alternative(candidate: TruckRoute, routes: list[TruckRoute]) -> bool:
    fastest = min(route.duration_seconds for route in routes)
    if candidate.duration_seconds > fastest * MAX_DURATION_RATIO:
        return False
    return all(shared_fraction(candidate.points, route.points) < MAX_SHARED_FRACTION for route in routes)


def _warnings(provider_count: int, total_count: int) -> list[str]:
    warnings = []
    generated = total_count - provider_count
    if generated:
        warnings.append(
            f"The routing provider returned {provider_count} route(s); "
            f"{generated} more generated through a detour waypoint."
        )
    if total_count < TARGET_ROUTE_COUNT:
        warnings.append(f"Only {total_count} distinct route(s) could be found for this trip.")
    return warnings
